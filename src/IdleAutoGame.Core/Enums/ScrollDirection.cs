namespace IdleAutoGame.Core.Enums;

/// <summary>
/// Direction for semantic scroll gestures.
/// </summary>
public enum ScrollDirection
{
    /// <summary>
    /// Scroll upwards (content moves down, viewport moves up).
    /// </summary>
    Up,

    /// <summary>
    /// Scroll downwards (content moves up, viewport moves down).
    /// </summary>
    Down,

    /// <summary>
    /// Scroll towards the left.
    /// </summary>
    Left,

    /// <summary>
    /// Scroll towards the right.
    /// </summary>
    Right
}

